function rememberMenuAudioPosition() {
    if (currentAudioSource && Number.isFinite(audio.currentTime)) {
        menuAudioPositions.set(currentAudioSource, audio.currentTime);
    }
}

function configureMenuAudioPlayback(source) {
    const themeSource = theme?.mainSong
        ? themeAssetUrl(theme, 'mus', theme.mainSong)
        : '';
    const isThemeTrack = source === themeSource;
    const configuredRate = isThemeTrack ? Number(theme?.musicPlaybackRate) : 1;
    const playbackRate = Number.isFinite(configuredRate)
        ? Math.min(2, Math.max(0.5, configuredRate))
        : 1;

    audio.defaultPlaybackRate = playbackRate;
    audio.playbackRate = playbackRate;
    if ('preservesPitch' in audio) {
        audio.preservesPitch = isThemeTrack
            ? theme?.musicPreservesPitch !== false
            : true;
    }
}

function switchMenuAudioSource(source) {
    rememberMenuAudioPosition();
    audio.pause();

    const resumeAt = menuAudioPositions.get(source) || 0;
    currentAudioSource = source;

    const restorePosition = () => {
        if (currentAudioSource !== source) return;

        const latestResumeAt = menuAudioPositions.get(source) || resumeAt;
        const maximumPosition = Number.isFinite(audio.duration)
            ? Math.max(0, audio.duration - 0.44)
            : latestResumeAt;
        audio.currentTime = Math.min(latestResumeAt, maximumPosition);
    };

    // Register before loading. WebView2 can briefly retain the previous track's
    // readyState after assigning src; restoring then is discarded when the new
    // media pipeline resets currentTime to zero.
    audio.addEventListener('loadedmetadata', restorePosition, { once: true });
    audio.src = source;
    configureMenuAudioPlayback(source);
    audio.load();
}

function loopMenuAudio() {
    const loopBuffer = 0.44;
    if (Number.isFinite(audio.duration) && audio.currentTime > audio.duration - loopBuffer) {
        audio.currentTime = 0;
        audio.play().catch(() => {});
    }
}

